import streamlit as st
import torch
import torchvision.transforms as transforms
from PIL import Image
from model import get_medical_model

st.set_page_config(page_title="AI Medical Imaging Insights", page_icon="🩻", layout="centered")
st.title("🩻 AI-Powered Chest X-Ray Analyzer")
st.write("Upload a digital chest X-ray image to scan for patterns consistent with Pneumonia.")

@st.cache_resource
def load_ai_engine():
    model = get_medical_model()
    model.eval()
    return model

model = load_ai_engine()

transform = transforms.Compose([
    transforms.Resize((224, 224)),
    transforms.ToTensor(),
    transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225])
])

uploaded_file = st.file_uploader("Choose a Chest X-ray image (JPEG/PNG)...", type=["jpg", "jpeg", "png"])

if uploaded_file is not None:
    image = Image.open(uploaded_file).convert("RGB")
    st.image(image, caption="Uploaded Chest X-ray Scan", use_container_width=True)
    
    with st.spinner("Analyzing radiological scan data..."):
        tensor = transform(image).unsqueeze(0)
        
        with torch.no_grad():
            outputs = model(tensor)
            probabilities = torch.nn.functional.softmax(outputs, dim=1)
            prediction = torch.argmax(probabilities).item()
            
        classes = ["Normal (No Infection Detected)", "Pneumonia Signs Detected"]
        confidence = probabilities[0][prediction].item() * 100
        
        st.subheader("Diagnostic Assessment Summary")
        if prediction == 0:
            st.success(f"**Result:** {classes[prediction]} (Confidence: {confidence:.2f}%)")
        else:
            st.error(f"**Result:** {classes[prediction]} (Confidence: {confidence:.2f}%)")
            st.warning("⚠️ **Notice:** This assessment is generated by an experimental AI model for portfolio demonstration purposes. Consult a medical professional.")
